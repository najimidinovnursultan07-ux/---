class Command(BaseCommand):
    help = "Create the initial active student list without duplicating existing names."

    def handle(self, *args, **options):
        created_count = 0
        for full_name in STUDENT_NAMES:
            _, created = Student.objects.get_or_create(full_name=full_name)
            created_count += int(created)

        self.stdout.write(
            self.style.SUCCESS(f"Seed complete: {created_count} new students added.")
        )
